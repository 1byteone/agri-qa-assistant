# ---------------------------------------------------------------
# 单位归一化：原始 CSV 为 产量(万吨)/面积(千公顷)，统一入库为 吨/亩
# ---------------------------------------------------------------
UNIT_TO_TONS = {"万吨": 10000.0, "吨": 1.0, "万公斤": 10.0, "公斤": 0.001}
UNIT_TO_MU = {"千公顷": 15000.0, "公顷": 15.0, "亩": 1.0, "万亩": 10000.0}


def normalize_unit(unit: str) -> tuple:
    """将任意单位换算为 (标准指标名, 标准单位, 换算系数)。

    返回 (indicator_name, unit_name, factor)，数值乘以 factor 即得到标准单位数值。
    """
    unit = (unit or "").strip()
    # 先按面积单位匹配（千公顷/公顷/亩/万亩）
    if unit in UNIT_TO_MU:
        return "面积", "亩", UNIT_TO_MU[unit]
    # 再按产量/重量单位匹配
    if unit in UNIT_TO_TONS:
        return "产量", "吨", UNIT_TO_TONS[unit]
    # 兜底：按名称模糊判断
    if "面积" in unit or "公顷" in unit or "亩" in unit:
        return "面积", "亩", UNIT_TO_MU.get(unit, 1.0)
    if "产量" in unit or "吨" in unit or "公斤" in unit:
        return "产量", "吨", UNIT_TO_TONS.get(unit, 1.0)
    raise ValueError(f"无法识别的单位: {unit}")


